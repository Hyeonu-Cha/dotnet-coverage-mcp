using DotNetCoverageMcp.Services;
using FluentAssertions;

namespace DotNetCoverageMcp.Tests.Unit;

public class SourceFileClassifierTests
{
    private static NonTargetKind? Kind(string text, string path = "Src/Some.cs") =>
        SourceFileClassifier.Classify(path, text)?.Kind;

    // --- Entry points ---

    [Theory]
    [InlineData("Program.cs")]
    [InlineData("Startup.cs")]
    public void EntryPointFileNames(string name) =>
        Kind("public class X { public void Run() { if (true) { } } }", $"Api/{name}").Should().Be(NonTargetKind.EntryPoint);

    [Fact]
    public void TopLevelStatements() =>
        Kind("var app = WebApplication.Create(); app.Run();", "Api/Host.cs").Should().Be(NonTargetKind.EntryPoint);

    [Fact]
    public void StaticMain() =>
        Kind("class Entry { static async Task Main(string[] args) { await Task.Yield(); } }").Should().Be(NonTargetKind.EntryPoint);

    // --- DI registration ---

    [Fact]
    public void ServiceCollectionExtensions() =>
        Kind("""
            public static class ServiceCollectionExtensions
            {
                public static IServiceCollection AddOrders(this IServiceCollection services)
                {
                    services.AddScoped<IOrderService, OrderService>();
                    return services;
                }
                public static WebApplication MapOrders(this WebApplication app) => app;
            }
            """).Should().Be(NonTargetKind.DiRegistration);

    [Fact]
    public void ExtensionsOnDomainTypes_AreTargets() =>
        Kind("public static class StringExtensions { public static bool IsBlank(this string s) => s.Trim().Length == 0; }")
            .Should().BeNull();

    // --- Generated ---

    [Theory]
    [InlineData("Api/Client.g.cs")]
    [InlineData("Forms/Main.Designer.cs")]
    [InlineData("Api/Client.generated.cs")]
    public void GeneratedFileNames(string path) =>
        Kind("public class X { public void M() { if (true) { } } }", path).Should().Be(NonTargetKind.Generated);

    [Fact]
    public void AutoGeneratedHeader() =>
        Kind("// <auto-generated>\n// This code was generated by a tool.\n// </auto-generated>\npublic class X { public void M() { } }")
            .Should().Be(NonTargetKind.Generated);

    [Theory]
    [InlineData("[System.CodeDom.Compiler.GeneratedCode(\"tool\", \"1\")]")]
    [InlineData("[ExcludeFromCodeCoverage]")]
    [InlineData("[System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute]")]
    public void GeneratedOrExcludedAttributes(string attribute) =>
        Kind($"{attribute} public class X {{ public void M() {{ if (true) {{ }} }} }}").Should().Be(NonTargetKind.Generated);

    // --- Models ---

    [Theory]
    [InlineData("public class OrderDto { public int Id { get; set; } public string Name { get; init; } = \"\"; }")]
    [InlineData("public record OrderRow(int Id, string Name);")]
    [InlineData("public enum Status { Open, Closed }")]
    [InlineData("public interface IOrderService { Task<Order> GetAsync(int id); }")]
    [InlineData("public class Person { public string First { get; set; } = \"\"; public string Last { get; set; } = \"\"; public string Full => $\"{First} {Last}\"; }")]
    [InlineData("public class Order { public Order(int id) { Id = id; } public int Id { get; } }")]
    [InlineData("public sealed class AppOptions { public const string Section = \"App\"; public int Retries { get; set; } = 3; }")]
    [InlineData("public class Outer { public int A { get; set; } public class Inner { public int B { get; set; } } }")]
    public void DataOnlyFiles_AreModels(string text) =>
        Kind(text).Should().Be(NonTargetKind.Model);

    // Look-alikes that hold logic and must stay targets.
    [Theory]
    [InlineData("public class Order { public decimal Total() => Lines.Sum(l => l.Price); public List<Line> Lines { get; } = new(); }")] // method
    [InlineData("public class Person { public int Age { get; set; } public bool IsAdult => Age >= 18 && Age < 150; }")]              // && is a branch
    [InlineData("public class Person { public string? Nick { get; set; } public string Display => Nick ?? \"anon\"; }")]               // ?? is a branch
    [InlineData("public class Order { public Order(string id) { ArgumentNullException.ThrowIfNull(id); Id = id; } public string Id { get; } }")] // guard
    [InlineData("public class Order { private int _q; public int Quantity { get => _q; set { if (value < 0) throw new ArgumentException(); _q = value; } } }")]
    [InlineData("public interface IClock { DateTime Now { get; } DateTime Today() => Now.Date; }")]                                  // default impl
    [InlineData("public class Dto { public int Id { get; set; } } public class OrderService { public int Count() => 1; }")]          // mixed file
    public void LogicFiles_AreTargets(string text) =>
        Kind(text).Should().BeNull();

    [Fact]
    public void Service_IsTarget() =>
        Kind("""
            namespace App;
            public class OrderService(IOrderRepository repo)
            {
                public async Task<bool> PlaceAsync(Order order)
                {
                    if (order.Lines.Count == 0) return false;
                    await repo.SaveAsync(order);
                    return true;
                }
            }
            """).Should().BeNull();

    [Theory]
    [InlineData("<PackageReference Include=\"Microsoft.NET.Test.Sdk\" Version=\"18.12.0\" />", true)]
    [InlineData("<PackageReference Include=\"xunit.v3\" />", true)]                 // MTP, no Test.Sdk
    [InlineData("<PackageReference Include=\"NUnit\" />", true)]
    [InlineData("<PackageReference Include=\"MSTest\" />", true)]
    [InlineData("<IsTestProject>true</IsTestProject>", true)]
    [InlineData("<PackageReference Include=\"Microsoft.Extensions.Hosting\" />", false)]
    [InlineData("<InternalsVisibleTo Include=\"App.Tests\" />", false)]
    public void IsTestProject(string itemXml, bool expected)
    {
        var path = Path.Combine(Path.GetTempPath(), $"{Guid.NewGuid():N}.csproj");
        File.WriteAllText(path, $"<Project Sdk=\"Microsoft.NET.Sdk\"><ItemGroup>{itemXml}</ItemGroup></Project>");
        try { SourceFileClassifier.IsTestProject(path).Should().Be(expected); }
        finally { File.Delete(path); }
    }

    [Fact]
    public void ReasonIsHumanReadable() =>
        SourceFileClassifier.Classify("Api/Program.cs", "app.Run();")!.Reason.Should().NotBeNullOrWhiteSpace();
}
