using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace DotNetCoverageMcp.Services;

public enum NonTargetKind { EntryPoint, DiRegistration, Generated, Model, TestCode }

public record NonTargetReason(NonTargetKind Kind, string Reason);

/// <summary>
/// Decides from a file's syntax alone whether it is worth writing tests for. Entry points,
/// DI registration, generated code and data-only models are not coverage targets: they
/// either can't reasonably reach the target or have nothing to test, and an agent asked to
/// get every file to 80% would otherwise cycle on them until it gives up.
/// </summary>
public static class SourceFileClassifier
{
    private static readonly string[] GeneratedSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"];
    private static readonly string[] EntryPointFileNames = ["Program.cs", "Startup.cs"];

    // Receivers of the usual `AddMyServices(this IServiceCollection services)` style.
    private static readonly HashSet<string> CompositionRootTypes =
    [
        "IServiceCollection", "IApplicationBuilder", "IEndpointRouteBuilder", "IHostBuilder",
        "IHostApplicationBuilder", "WebApplicationBuilder", "WebApplication", "IMvcBuilder"
    ];

    /// <summary>Returns why the file is not a test target, or null when it is one.</summary>
    public static NonTargetReason? Classify(string path, string text)
    {
        var fileName = Path.GetFileName(path);

        if (GeneratedSuffixes.Any(s => fileName.EndsWith(s, StringComparison.OrdinalIgnoreCase)))
            return new(NonTargetKind.Generated, "generated file name");

        var root = CSharpSyntaxTree.ParseText(text).GetCompilationUnitRoot();

        if (root.GetLeadingTrivia().ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
            return new(NonTargetKind.Generated, "<auto-generated> header");

        if (EntryPointFileNames.Contains(fileName, StringComparer.OrdinalIgnoreCase))
            return new(NonTargetKind.EntryPoint, fileName);
        if (root.Members.OfType<GlobalStatementSyntax>().Any())
            return new(NonTargetKind.EntryPoint, "top-level statements");
        if (root.DescendantNodes().OfType<MethodDeclarationSyntax>().Any(IsMain))
            return new(NonTargetKind.EntryPoint, "static Main");

        // Top-level types; nested types are judged together with their parent.
        var types = root.DescendantNodes(n => n is not BaseTypeDeclarationSyntax)
            .OfType<BaseTypeDeclarationSyntax>()
            .ToList();
        var delegates = root.DescendantNodes().OfType<DelegateDeclarationSyntax>().Any();
        if (types.Count == 0)
            return new(NonTargetKind.Model, delegates ? "delegates only" : "no types: nothing to test");

        if (types.All(t => HasAttribute(t, "GeneratedCode")))
            return new(NonTargetKind.Generated, "[GeneratedCode]");
        if (types.All(t => HasAttribute(t, "ExcludeFromCodeCoverage")))
            return new(NonTargetKind.Generated, "[ExcludeFromCodeCoverage]");

        if (types.All(IsCompositionRoot))
            return new(NonTargetKind.DiRegistration, "only service/app registration extension methods");

        if (types.All(IsDataOnly))
            return new(NonTargetKind.Model, "data only: properties, fields, enums or interfaces, no logic");

        return null;
    }

    // Package or SDK markers of a test project. Microsoft.NET.Test.Sdk alone is not enough:
    // xUnit v3 and other Microsoft.Testing.Platform projects can omit it.
    private static readonly string[] TestProjectMarkers =
    [
        "Microsoft.NET.Test.Sdk", "<IsTestProject>true", "MSTest.Sdk", "Include=\"xunit", "Include=\"NUnit", "Include=\"MSTest"
    ];

    /// <summary>Whether the .csproj at this path is a test project. Unreadable counts as no.</summary>
    public static bool IsTestProject(string csprojPath)
    {
        try
        {
            var text = File.ReadAllText(csprojPath);
            return TestProjectMarkers.Any(m => text.Contains(m, StringComparison.OrdinalIgnoreCase));
        }
        catch (IOException) { return false; }
        catch (UnauthorizedAccessException) { return false; }
    }

    private static bool IsMain(MethodDeclarationSyntax m) =>
        m.Identifier.Text == "Main" && m.Modifiers.Any(SyntaxKind.StaticKeyword);

    private static bool HasAttribute(MemberDeclarationSyntax member, string name) =>
        member.AttributeLists.SelectMany(l => l.Attributes).Any(a =>
        {
            var n = a.Name.ToString();
            n = n[(n.LastIndexOf('.') + 1)..];
            return n == name || n == name + "Attribute";
        });

    private static bool IsCompositionRoot(BaseTypeDeclarationSyntax type)
    {
        if (type is not ClassDeclarationSyntax c || !c.Modifiers.Any(SyntaxKind.StaticKeyword)) return false;
        var methods = c.Members.OfType<MethodDeclarationSyntax>().ToList();
        return methods.Count > 0 && methods.All(m =>
        {
            var first = m.ParameterList.Parameters.FirstOrDefault();
            if (first == null || !first.Modifiers.Any(SyntaxKind.ThisKeyword) || first.Type == null) return false;
            var typeName = first.Type.ToString();
            typeName = typeName[(typeName.LastIndexOf('.') + 1)..];
            return CompositionRootTypes.Contains(typeName);
        });
    }

    private static bool IsDataOnly(BaseTypeDeclarationSyntax type) => type switch
    {
        EnumDeclarationSyntax => true,
        // Interface members are declarations unless they carry a default implementation.
        InterfaceDeclarationSyntax i => i.Members.All(m => m switch
        {
            MethodDeclarationSyntax md => md.Body == null && md.ExpressionBody == null,
            PropertyDeclarationSyntax p => IsDataProperty(p),
            _ => true
        }),
        TypeDeclarationSyntax t => t.Members.All(IsDataMember),
        _ => false
    };

    private static bool IsDataMember(MemberDeclarationSyntax member) => member switch
    {
        FieldDeclarationSyntax f => f.Declaration.Variables.All(v => v.Initializer == null || !HasBranching(v.Initializer.Value)),
        EventFieldDeclarationSyntax => true,
        PropertyDeclarationSyntax p => IsDataProperty(p),
        ConstructorDeclarationSyntax c => IsAssignmentOnly(c),
        BaseTypeDeclarationSyntax nested => IsDataOnly(nested),
        DelegateDeclarationSyntax => true,
        // Methods, operators, indexers, finalizers, conversions: logic worth testing.
        _ => false
    };

    // Auto-properties, and accessors or `=>` bodies that are a single expression with no branch.
    private static bool IsDataProperty(PropertyDeclarationSyntax p)
    {
        if (p.ExpressionBody != null) return !HasBranching(p.ExpressionBody.Expression);
        if (p.Initializer != null && HasBranching(p.Initializer.Value)) return false;
        return p.AccessorList == null || p.AccessorList.Accessors.All(a =>
            a.Body == null && (a.ExpressionBody == null || !HasBranching(a.ExpressionBody.Expression)));
    }

    private static bool IsAssignmentOnly(ConstructorDeclarationSyntax c)
    {
        if (c.ExpressionBody != null)
            return c.ExpressionBody.Expression is AssignmentExpressionSyntax a && !HasBranching(a.Right);
        return c.Body == null || c.Body.Statements.All(s =>
            s is ExpressionStatementSyntax { Expression: AssignmentExpressionSyntax a } && !HasBranching(a.Right));
    }

    // Constructs that compile to branches: once present, there is something to cover.
    private static bool HasBranching(SyntaxNode node) =>
        node.DescendantNodesAndSelf().Any(n => n.Kind() is
            SyntaxKind.ConditionalExpression or SyntaxKind.CoalesceExpression or SyntaxKind.CoalesceAssignmentExpression or
            SyntaxKind.ConditionalAccessExpression or SyntaxKind.SwitchExpression or SyntaxKind.IsPatternExpression or
            SyntaxKind.LogicalAndExpression or SyntaxKind.LogicalOrExpression or SyntaxKind.ThrowExpression or
            SyntaxKind.SimpleLambdaExpression or SyntaxKind.ParenthesizedLambdaExpression or SyntaxKind.AnonymousMethodExpression);
}
